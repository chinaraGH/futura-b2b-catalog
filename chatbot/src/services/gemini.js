// ─── Генерация ответа ────────────────────────────────────────────────────────
/**
 * @param {Array<{role:'user'|'model', parts:[{text:string}]}>} history
 * @param {string} userText
 * @param {string} ragContext  строка с найденными товарами
 * @returns {Promise<string>}
 */
async function chat(history, userText, ragContext = '', retries = 2) {
  const systemInstruction = SYSTEM_PROMPT.replace('{RAG_CONTEXT}', ragContext || 'Нет релевантных данных в базе.');

  const model = genai.chats.create({
    model: 'gemini-3.6-flash',
    config: {
      systemInstruction,
      temperature: 0.4,
      maxOutputTokens: 1024,
    },
    history,
  });

  for (let i = 0; i <= retries; i++) {
    try {
      const response = await model.sendMessage({ message: userText });
      return response.text.trim();
    } catch (err) {
      const is503 = err.status === 503 || (err.message && err.message.includes('"code":503'));
      if (i === retries || !is503) {
        throw err;
      }
      // Ждем перед повторной попыткой (exponential backoff)
      await new Promise(resolve => setTimeout(resolve, 1000 * Math.pow(2, i)));
    }
  }
}

// ─── Генерация эмбеддинга ────────────────────────────────────────────────────
/**
 * @param {string} text
 * @returns {Promise<number[]>}
 */
async function embedText(text) {
  const response = await genai.models.embedContent({
    model: 'gemini-embedding-2',
    contents: text,
  });
  // gemini-embedding-001 → 3072 dims (MRL). Обрезаем до 768 (размер колонки в БД).
  return response.embeddings[0].values.slice(0, 768);
}

module.exports = { chat, embedText };
